#!/usr/bin/env python3
"""Static sanity checks for the QuickTap POS sources.

No JDK / Android SDK is available in this workspace, so the app cannot be
compiled here. These checks catch the classes of mistake a compile would catch
for the parts that are pure text: unbalanced braces, dangling class references,
layouts binding to ids that do not exist, and activities started but never
declared in the manifest.

Run:  python3 tools/check_sources.py
"""
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(os.path.join(__file__, os.pardir)))
SRC = os.path.join(ROOT, 'app', 'src', 'main')
JAVA = os.path.join(SRC, 'java')
RES = os.path.join(SRC, 'res')

errors = []
warnings = []


def walk(folder, ext):
    for base, _, files in os.walk(folder):
        for name in sorted(files):
            if name.endswith(ext):
                yield os.path.join(base, name)


def rel(path):
    return os.path.relpath(path, ROOT)


def strip_noise(text):
    """Remove comments, string and char literals, keeping line structure."""
    out = []
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        two = text[i:i + 2]
        if two == '//':
            j = text.find('\n', i)
            i = n if j < 0 else j
            continue
        if two == '/*':
            j = text.find('*/', i + 2)
            j = n if j < 0 else j + 2
            out.append('\n' * text.count('\n', i, j))
            i = j
            continue
        if c in '"\'':
            quote, i = c, i + 1
            while i < n:
                if text[i] == '\\':
                    i += 2
                    continue
                if text[i] == quote:
                    i += 1
                    break
                if text[i] == '\n':      # unterminated literal
                    break
                i += 1
            out.append('""')
            continue
        out.append(c)
        i += 1
    return ''.join(out)


# ---------------------------------------------------------------- java checks

java_files = list(walk(JAVA, '.java'))
defined = {}
for path in java_files:
    body = io.open(path, encoding='utf-8').read()
    clean = strip_noise(body)
    name = os.path.splitext(os.path.basename(path))[0]
    defined[name] = path
    for open_c, close_c, label in (('{', '}', 'braces'), ('(', ')', 'parentheses')):
        if clean.count(open_c) != clean.count(close_c):
            errors.append('%s: unbalanced %s (%d %s vs %d %s)' % (
                rel(path), label, clean.count(open_c), open_c,
                clean.count(close_c), close_c))
    if 'package ' not in clean:
        errors.append('%s: no package declaration' % rel(path))


def class_name_from_file(path):
    return os.path.splitext(os.path.basename(path))[0]


# every "import com.quicktap.pos.X" must resolve to a file that exists
pkg_root = os.path.join(JAVA, 'com', 'quicktap', 'pos')
for path in java_files:
    body = io.open(path, encoding='utf-8').read()
    for imp in re.findall(r'import\s+(com\.quicktap\.pos\.[\w.]+);', body):
        tail = imp.split('com.quicktap.pos.', 1)[1]
        # R, BuildConfig and ViewBinding classes are generated by the build.
        if tail.startswith(('R', 'BuildConfig', 'databinding.')):
            continue
        # Class, or Class.Inner, or a static member: strip the member.
        parts = tail.split('.')
        candidates = []
        for cut in range(len(parts), 0, -1):
            candidates.append(os.path.join(pkg_root, *parts[:cut]) + '.java')
        if not any(os.path.exists(c) for c in candidates):
            errors.append('%s: import %s resolves to no source file' % (rel(path), imp))

# references to the obfuscated 类NNN helpers must exist somewhere
for path in java_files:
    body = strip_noise(io.open(path, encoding='utf-8').read())
    for ref in sorted(set(re.findall(r'类(\d{3})', body))):
        if ('类%s' % ref) not in defined:
            errors.append('%s: reference to missing class 类%s' % (rel(path), ref))

    # every 类NNN.java file should be referenced or be a top-level entry point
    app_path = os.path.join(pkg_root, '类001.java')
for name, path in sorted(defined.items()):
    if name.startswith('类') and path != app_path:
        hits = 0
        for other in java_files:
            if other == path:
                continue
            if name in io.open(other, encoding='utf-8').read():
                hits += 1
        if hits == 0:
            warnings.append('%s: not referenced by any other source file' % rel(path))


# --------------------------------------------------------------- resource ids

ids = set(re.findall(r'@\+id/([\w.]+)',
                     '\n'.join(io.open(p, encoding='utf-8').read()
                               for p in walk(RES, '.xml'))))
# colours come from values/colors.xml AND from the color state lists in res/color
declared_colors = set()
for folder in ('values', 'values-night'):
    folder = os.path.join(RES, folder)
    if os.path.isdir(folder):
        for path in walk(folder, '.xml'):
            declared_colors |= set(re.findall(
                r'<color name="([\w.]+)"', io.open(path, encoding='utf-8').read()))
colour_dir = os.path.join(RES, 'color')
if os.path.isdir(colour_dir):
    declared_colors |= {os.path.splitext(n)[0] for n in os.listdir(colour_dir)}

# ids owned by the framework / Material, never declared in this repo's layouts
EXTERNAL_IDS = {'content', 'design_bottom_sheet', 'home', 'text', 'icon',
                'title', 'message', 'button1', 'button2', 'button3'}

for path in java_files:
    body = strip_noise(io.open(path, encoding='utf-8').read())
    for rid in set(re.findall(r'(?<!android\.)\bR\.id\.(\w+)', body)):
        if rid not in ids and rid not in EXTERNAL_IDS:
            errors.append('%s: R.id.%s is not declared in any layout' % (rel(path), rid))
    for rid in set(re.findall(r'(?<!android\.)\bR\.color\.(\w+)', body)):
        if rid not in declared_colors:
            errors.append('%s: R.color.%s is not declared in values/' % (rel(path), rid))

for path in walk(RES, '.xml'):
    body = io.open(path, encoding='utf-8').read()
    for rid in set(re.findall(r'@\+id/(\w+)', body)):
        if rid not in ids:
            errors.append('%s: id @+id/%s missing' % (rel(path), rid))
    for color in set(re.findall(r'@color/([\w.]+)', body)):
        if color not in declared_colors:
            errors.append('%s: @color/%s is not declared in values/' % (rel(path), color))

# --------------------------------------------------------- manifest vs sources

manifest = io.open(os.path.join(SRC, 'AndroidManifest.xml'), encoding='utf-8').read()
declared = set(re.findall(r'android:name="(\.[\w.]+|com\.quicktap\.pos\.[\w.]+)"', manifest))
declared_full = {d if d.startswith('com.') else 'com.quicktap.pos' + d for d in declared}

for path in java_files:
    body = strip_noise(io.open(path, encoding='utf-8').read())
    if not re.search(r'class\s+\w+\s+extends\s+(androidx\.)?(AppCompat)?Activity', body):
        continue
    package = re.search(r'package\s+([\w.]+);', body).group(1)
    cls = class_name_from_file(path)
    fq = package + '.' + cls
    if fq in declared_full:
        continue
    started = False
    for other in java_files:
        text = strip_noise(io.open(other, encoding='utf-8').read())
        if re.search(r'(Intent|startActivity)[^;]*\b%s\.class' % re.escape(cls),
                     text, re.S):
            started = True
            break
    if started:
        errors.append('%s: %s is started but not declared in AndroidManifest.xml'
                      % (rel(path), fq))

# ------------------------------------------------------------ banned leftovers

banned = {
    'v1/theme': 'server colour plumbing must be gone',
    'v1/splash': 'remote splash plumbing must be gone',
    'isDemoMode': 'the licence bypass must be gone',
    'setDemoMode': 'the licence bypass must be gone',
    'theme_primary': 'colour prefs must be gone',
    'theme_secondary': 'colour prefs must be gone',
    'getSplashAccentColor': 'remote splash colour must be gone',
    'CloudSync': 'the paid Cloud Sync add-on was deleted; v1/sync/push|pull is the only sync',
    'cloudsync': 'the paid Cloud Sync add-on was deleted (package, db name, prefs)',
    '类037': 'the runtime repaint class is deleted — no view-tree colouring may come back',
    '类039': 'the colour presets are deleted — the server has no colour input at all',
}
for path in java_files + [os.path.join(SRC, 'AndroidManifest.xml')]:
    body = io.open(path, encoding='utf-8').read()
    for needle, why in banned.items():
        if needle in body:
            errors.append('%s: still contains %r (%s)' % (rel(path), needle, why))

# File names are part of the contract: a `#U7c7bNNN.java` file never compiles, because
# javac requires the file name to match the public class it declares. Renaming the
# classes is only protection if the tree still builds, so this is checked, not assumed.
public_class = re.compile(r'^\s*public\s+(?:final\s+|abstract\s+)?(?:class|interface|enum)\s+(\w+)',
                          re.MULTILINE)
for path in java_files:
    base = os.path.basename(path)
    if '#U7c7b' in base or '\\u' in base.lower():
        errors.append('%s: escaped file name — javac cannot read this' % rel(path))
        continue
    body = io.open(path, encoding='utf-8').read()
    match = public_class.search(body)
    if match and match.group(1) + '.java' != base:
        errors.append('%s: declares public class %s but the file is named %s'
                      % (rel(path), match.group(1), base))

print('checked %d java files' % len(java_files))
for w in warnings:
    print('  note: ' + w)
if errors:
    print('\n%d PROBLEM(S):' % len(errors))
    for e in errors:
        print('  ✗ ' + e)
    sys.exit(1)
print('\nOK — no dangling references, layouts and manifest agree.')
